package team

import (
	"context"
	"errors"
	"fmt"
	"strings"

	"charm.land/fantasy"
)

const (
	coordinatorPolicyRepairPrefix          = "COORDINATOR POLICY REPAIR REQUIRED:"
	coordinatorPolicyRepairExhaustedPrefix = "COORDINATOR POLICY REPAIR EXHAUSTED:"
	maxCoordinatorPolicyRepairs            = 2
)

var errCoordinatorPolicyRepairExhausted = errors.New("coordinator policy repair budget exhausted")

// delegationPolicyViolation is deliberately distinct from ordinary execution
// failures.  The coordinator may repair a rejected delegation, but must never
// turn a worker/tool failure into a policy-repair opportunity.
type delegationPolicyViolation struct{ message string }

func (e *delegationPolicyViolation) Error() string {
	if e == nil {
		return "delegation policy violation"
	}
	return "delegation policy violation: " + e.message
}

func isCoordinatorPolicyRepairResult(result string) bool {
	trimmed := strings.TrimSpace(result)
	return strings.HasPrefix(trimmed, coordinatorPolicyRepairPrefix) || strings.HasPrefix(trimmed, coordinatorPolicyRepairExhaustedPrefix)
}

// coordinatorPolicyRepairPrompt returns a deterministic, bounded correction
// instruction. It is intentionally generated by the runtime rather than an
// LLM so the repair cannot mutate its own safety requirements.
func (c *Coordinator) coordinatorPolicyRepairPrompt(violation error) (string, bool) {
	attempt := c.coordinatorPolicyRepairsAttempt.Add(1)
	reason := strings.TrimSpace(violation.Error())
	if attempt > maxCoordinatorPolicyRepairs {
		c.coordinatorPolicyRepairPending.Store(false)
		c.wrapUp.Store(1)
		c.report(c.newEvent("policy_decision").withTodoID(CoordTodoID).withMessage(fmt.Sprintf("coordinator delegation policy repair exhausted at attempt %d/%d: %s", attempt, maxCoordinatorPolicyRepairs, reason)))
		return fmt.Sprintf("%s repair attempts exhausted (%d/%d). No further delegation is permitted; the runtime will produce an LLM-free summary. Violation: %s", coordinatorPolicyRepairExhaustedPrefix, attempt, maxCoordinatorPolicyRepairs, reason), true
	}
	c.coordinatorPolicyRepairPending.Store(true)
	c.report(c.newEvent("policy_decision").withTodoID(CoordTodoID).withMessage(fmt.Sprintf("coordinator delegation policy repair requested at attempt %d/%d: %s", attempt, maxCoordinatorPolicyRepairs, reason)))
	return fmt.Sprintf("%s\nAttempt %d/%d\nViolation: %s\n\nDeterministic repair instructions:\n- The next coordinator action may only be a delegation of unfinished work or a direct finish call.\n- Do not dispatch any worker with a terminal done result.\n- Dispatch only unfinished work that is still required.\n- If no unfinished work remains, call finish directly.\n- Do not retry the rejected delegation unchanged.", coordinatorPolicyRepairPrefix, attempt, maxCoordinatorPolicyRepairs, reason), false
}

func (c *Coordinator) coordinatorPolicyRepairResponse(violation error) fantasy.ToolResponse {
	prompt, _ := c.coordinatorPolicyRepairPrompt(violation)
	return fantasy.NewTextErrorResponse(prompt)
}

func (c *Coordinator) finalizeCoordinatorPolicyRepairRun() string {
	const reason = "coordinator delegation policy repair budget exhausted; no further coordinator delegation is permitted"
	if c == nil {
		return reason
	}
	c.coordinatorPolicyRepairPending.Store(false)
	items := []*TodoItem(nil)
	if c.taskTracker != nil && c.taskTracker.TodoList() != nil {
		items = c.taskTracker.TodoList().Items()
	}
	summary := reason
	if c.taskTracker != nil && c.taskTracker.TodoList() != nil {
		if evidence := c.summaryFromTodos(errors.New(reason)); evidence != "" {
			summary = evidence
		}
	}
	evaluated := EvaluateRunOutcome(RunEvaluationInput{
		UnresolvedTasks: UnresolvedTaskReferences(items),
		Acceptance:      AcceptanceNotConfigured,
		Response:        summary,
		Reason:          reason,
		Stats:           SummarizeRunStats(items),
		Metrics:         c.Metrics(),
		GoalMode:        c.GoalMode(),
	})
	c.FinalizeRun(context.Background(), &evaluated, nil)
	c.finishCalled.Store(true)
	c.SetCurrentStage("coordinator_policy_repair_exhausted")
	return summary
}
